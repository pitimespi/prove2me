#!/usr/bin/env python3
"""Root-cause diagnostics for the nine CoreTxTests mismatches (REVIEW_DIFFTEST.md): emits
`tests/CoreTxMismatches.lean`, which re-checks each signature involved with
`BitcoinSig.checkECDSASignature` against (a) the scriptCode Core uses (the code after the executed
`OP_CODESEPARATOR`, or with every multisig signature deleted) and (b) the scriptCode the Lean model uses
(the whole script, with only the checked signature deleted). Every `#eval` carries its expected value.

Run with `python3 -I core_tx_mismatches.py <tx_valid.json> <tx_invalid.json> <out dir>`.
"""
import json, struct, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from core_script_tests import parse_script  # noqa: E402

valid_path = sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/coretests/tx_valid.json'
invalid_path = sys.argv[2] if len(sys.argv) > 2 else '/tmp/claude-0/coretests/tx_invalid.json'
out_dir = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
idx = {}
for kind, path in (('valid', valid_path), ('invalid', invalid_path)):
    for i, e in enumerate(json.load(open(path))):
        if len(e) > 1 and isinstance(e[0], list):
            idx['%s#%d' % (kind, i)] = {'raw': e}

def rd_cs(b, i):
    c = b[i]
    if c < 253: return c, i+1
    if c == 253: return struct.unpack('<H', b[i+1:i+3])[0], i+3
    if c == 254: return struct.unpack('<I', b[i+1:i+5])[0], i+5
    return struct.unpack('<Q', b[i+1:i+9])[0], i+9
def rd_bytes(b, i):
    n, i = rd_cs(b, i); return b[i:i+n], i+n
def parse_tx(h):
    b = bytes.fromhex(h); i = 4
    nvin, i = rd_cs(b, i); seg = False
    if nvin == 0:
        flag = b[i]; i += 1; seg = flag == 1; nvin, i = rd_cs(b, i)
    vin = []
    for _ in range(nvin):
        ph = b[i:i+32]; n = struct.unpack('<I', b[i+32:i+36])[0]; i += 36
        sig, i = rd_bytes(b, i); seq = struct.unpack('<I', b[i:i+4])[0]; i += 4
        vin.append({'hash': ph, 'n': n, 'sig': sig, 'seq': seq, 'wit': []})
    nvout, i = rd_cs(b, i); vout = []
    for _ in range(nvout):
        v = struct.unpack('<q', b[i:i+8])[0]; i += 8; spk, i = rd_bytes(b, i); vout.append((v, spk))
    if seg:
        for v in vin:
            k, i = rd_cs(b, i); w = []
            for _ in range(k):
                e, i = rd_bytes(b, i); w.append(e)
            v['wit'] = w
    return vin, vout
def pushes(script):
    """the data pushes of a script, in order"""
    out = []; i = 0
    while i < len(script):
        op = script[i]; i += 1
        if op <= 0x4e:
            if op < 0x4c: n = op
            elif op == 0x4c: n = script[i]; i += 1
            elif op == 0x4d: n = struct.unpack('<H', script[i:i+2])[0]; i += 2
            else: n = struct.unpack('<I', script[i:i+4])[0]; i += 4
            out.append(script[i:i+n]); i += n
        else: out.append(op)
    return out

L = []
def P(s): L.append(s)
P('''import Definitions.Def_BitcoinBlockV2
open BitcoinSer BitcoinSig BitcoinVerify BitcoinTaproot BitcoinBlockV2
/-! Root-cause diagnostics for the nine CoreTxTests mismatches (generated by tests/reference/core_tx_mismatches.py).
`chk` is `GenericTransactionSignatureChecker::CheckECDSASignature` on an explicit scriptCode: the
one Core uses (after the executed `OP_CODESEPARATOR`, or with every multisig signature deleted) versus
the one the Lean model uses (the whole script, with only the checked signature deleted). -/
def hexVal (c : Char) : Nat := if c.isDigit then c.toNat - 48 else c.toLower.toNat - 87
def ofHexL : List Char → Bytes
  | a :: b :: r => BitVec.ofNat 8 (hexVal a * 16 + hexVal b) :: ofHexL r
  | _ => []
def ofHex (s : String) : Bytes := ofHexL s.toList
def txOf (h : String) : Tx := ((readTx true (ofHex h)).map Prod.fst).getD ⟨0, [], [], 0⟩
def chk (txH : String) (nIn : Nat) (amount : Int) (v : SigVersion) (sigH pkH scH : String) : Bool :=
  checkECDSASignature (txOf txH) nIn amount v (ofHex sigH) (ofHex pkH) (ofHex scH)
def allF : BitcoinActivation.ScriptFlags := ⟨true, true, true, true, true, true, true⟩
/-- `VerifyScript` on input `i` alone. -/
def inp (txH : String) (i : Nat) (spkH : String) (amount : Int) (spent : List TxOut) : Bool :=
  let tx := txOf txH
  let x := tx.vin.getD i ⟨⟨[], 0⟩, [], 0, []⟩
  verifyScriptFull spent ⟨allF, tx, i, amount⟩ x.scriptSig (ofHex spkH) x.witness
''')
def spk_of(t, k): return parse_script(t['raw'][0][k][2]).hex()
def amt_of(t, k): return int(t['raw'][0][k][3]) if len(t['raw'][0][k]) >= 4 else 0
def spent_of(t): return '[' + ', '.join('⟨(%d : Int), ofHex "%s"⟩' % (amt_of(t, k), spk_of(t, k)) for k in range(len(t['raw'][0]))) + ']'

# ---- valid#79: <pk> CODESEPARATOR CHECKSIG
t = idx['valid#79']; tx = t['raw'][1]; vin, _ = parse_tx(tx)
sig = pushes(vin[0]['sig'])[0].hex(); spk = spk_of(t, 0); pk = spk[2:68]
P('-- valid#79: scriptPubKey = <pk> CODESEPARATOR CHECKSIG; Core scriptCode = "ac"; Lean = whole script')
P('#eval chk "%s" 0 0 .base "%s" "%s" "ac"   -- Core scriptCode: expect true' % (tx, sig, pk))
P('#eval chk "%s" 0 0 .base "%s" "%s" "%s"   -- Lean scriptCode (whole script): expect false' % (tx, sig, pk, spk))
# ---- valid#81
t = idx['valid#81']; tx = t['raw'][1]; vin, _ = parse_tx(tx)
sig1, sig2 = [p.hex() for p in pushes(vin[0]['sig'])]; spk = spk_of(t, 0); pk = spk[2:68]
P('-- valid#81: <pk> CHECKSIGVERIFY CODESEPARATOR <pk> CHECKSIGVERIFY CODESEPARATOR 1; sig2 (top) checked first with the whole script, sig1 with the code after the first CODESEPARATOR')
P('#eval chk "%s" 0 0 .base "%s" "%s" "%s"   -- sig2, whole script (Core = Lean): expect true' % (tx, sig2, pk, spk))
P('#eval chk "%s" 0 0 .base "%s" "%s" "%s"   -- sig1, Core scriptCode after CODESEPARATOR: expect true' % (tx, sig1, pk, '21' + pk + 'adab51'))
P('#eval chk "%s" 0 0 .base "%s" "%s" "%s"   -- sig1, Lean scriptCode (whole script): expect false' % (tx, sig1, pk, spk))
# ---- valid#85 and invalid#62
for tid in ['valid#85', 'invalid#62']:
    t = idx[tid]; tx = t['raw'][1]; vin, _ = parse_tx(tx)
    sig = pushes(vin[0]['sig'])[0].hex(); spk = spk_of(t, 0); pk = spk[8:74]
    assert spk == '63ab6821' + pk + 'adab51', spk
    P('-- %s: IF CODESEPARATOR ENDIF <pk> CHECKSIGVERIFY CODESEPARATOR 1 with scriptSig <sig> 1 (IF executed)' % tid)
    P('#eval chk "%s" 0 0 .base "%s" "%s" "%s"   -- Core scriptCode after the executed CODESEPARATOR: expect %s' % (tx, sig, pk, '6821' + pk + 'adab51', 'true' if tid == 'valid#85' else 'false'))
    P('#eval chk "%s" 0 0 .base "%s" "%s" "%s"   -- Lean scriptCode (whole script): expect %s' % (tx, sig, pk, spk, 'false' if tid == 'valid#85' else 'true'))
# ---- valid#96
t = idx['valid#96']; tx = t['raw'][1]; vin, _ = parse_tx(tx)
P('-- valid#96: input 0 (P2PKH) and input 1 (P2SH 2-of-3 whose redeemScript embeds the SIGHASH_SINGLE-bug signature)')
P('#eval inp "%s" 0 "%s" 0 %s   -- input 0 alone: expect true' % (tx, spk_of(t, 0), spent_of(t)))
P('#eval inp "%s" 1 "%s" 0 %s   -- input 1 alone (Lean): expect false' % (tx, spk_of(t, 1), spent_of(t)))
ps = pushes(vin[1]['sig']); dummy, sigA, sigB, redeem = ps
rp = pushes(redeem); assert rp[0] == 0x52 and rp[4] == 0x53 and rp[5] == 0xae and rp[1] == sigA
pk = rp[2].hex()
core_sc = '5221' + pk + '21' + pk + '53ae'
lean_sc = redeem.hex()   # sigB is not in the script, so FindAndDelete(sigB) leaves it unchanged
P('#eval chk "%s" 1 0 .base "%s" "%s" "%s"   -- sigB (SIGHASH_ALL) against key3, Core scriptCode (both sigs deleted): expect true' % (tx, sigB.hex(), pk, core_sc))
P('#eval chk "%s" 1 0 .base "%s" "%s" "%s"   -- sigB, Lean scriptCode (only sigB deleted, sigA still embedded): expect false' % (tx, sigB.hex(), pk, lean_sc))
P('#eval chk "%s" 1 0 .base "%s" "%s" "%s"   -- sigA (SIGHASH_SINGLE bug, digest 1) against key2: expect true under both' % (tx, sigA.hex(), pk, core_sc))
# ---- valid#244
t = idx['valid#244']; tx = t['raw'][1]; vin, _ = parse_tx(tx)
ps = pushes(vin[0]['sig']); dummy, sig1, sig2, two, key1, key2, redeem = ps
rp = pushes(redeem); assert rp == [0x52, 0xaf, sig1, sig2, 0x75]
P('-- valid#244: P2SH redeemScript = 2 CHECKMULTISIGVERIFY <sig1> <sig2> DROP; Core deletes both signatures before hashing, Lean only the one being checked')
P('#eval chk "%s" 0 200000 .base "%s" "%s" "52af75"   -- sig2 (checked first, against key2), Core scriptCode: expect true' % (tx, sig2.hex(), key2.hex()))
P('#eval chk "%s" 0 200000 .base "%s" "%s" "%s"   -- sig2, Lean scriptCode (sig1 still embedded): expect false' % (tx, sig2.hex(), key2.hex(), '52af' + ('48' + sig1.hex()) + '75'))
P('#eval chk "%s" 0 200000 .base "%s" "%s" "52af75"   -- sig1 against key1, Core scriptCode: expect true' % (tx, sig1.hex(), key1.hex()))
# ---- valid#222
t = idx['valid#222']; tx = t['raw'][1]; vin, _ = parse_tx(tx)
w = vin[1]['wit']; ws = w[-1]; wp = pushes(ws); pk1 = wp[0].hex(); pk2 = wp[3].hex()
assert wp[1] == 0xad and wp[2] == 0xab and wp[4] == 0xac
P('-- valid#222: input 1 is P2WSH <pk1> CHECKSIGVERIFY CODESEPARATOR <pk2> CHECKSIG, witness [w0, w1, script]; CHECKSIGVERIFY takes w1 with the whole script, CHECKSIG takes w0 with the code after CODESEPARATOR')
P('#eval inp "%s" 0 "%s" %d %s   -- input 0 alone: expect true' % (tx, spk_of(t, 0), amt_of(t, 0), spent_of(t)))
P('#eval inp "%s" 1 "%s" %d %s   -- input 1 alone (Lean): expect false' % (tx, spk_of(t, 1), amt_of(t, 1), spent_of(t)))
P('#eval chk "%s" 1 %d .witnessV0 "%s" "%s" "%s"   -- w1 with pk1, whole script (Core = Lean): expect true' % (tx, amt_of(t, 1), w[1].hex(), pk1, ws.hex()))
P('#eval chk "%s" 1 %d .witnessV0 "%s" "%s" "%s"   -- w0 with pk2, Core scriptCode after CODESEPARATOR: expect true' % (tx, amt_of(t, 1), w[0].hex(), pk2, '21' + pk2 + 'ac'))
P('#eval chk "%s" 1 %d .witnessV0 "%s" "%s" "%s"   -- w0 with pk2, Lean scriptCode (whole script): expect false' % (tx, amt_of(t, 1), w[0].hex(), pk2, ws.hex()))
# ---- valid#224 / #226
for tid in ['valid#224', 'valid#226']:
    t = idx[tid]; tx = t['raw'][1]; vin, _ = parse_tx(tx)
    for k in range(2):
        w = vin[k]['wit']; ws = w[-1]; wp = pushes(ws)
        executed = wp[0] == 0x51
        pk = wp[4].hex()
        P('-- %s input %d: P2WSH %s IF CODESEPARATOR ENDIF <pk> CHECKSIG (%s)' % (tid, k, '1' if executed else '0', 'CODESEPARATOR executed' if executed else 'unexecuted'))
        P('#eval inp "%s" %d "%s" %d %s   -- input %d alone (Lean): expect %s' % (tx, k, spk_of(t, k), amt_of(t, k), spent_of(t), k, 'false' if executed else 'true'))
        if executed:
            P('#eval chk "%s" %d %d .witnessV0 "%s" "%s" "%s"   -- Core scriptCode after CODESEPARATOR: expect true' % (tx, k, amt_of(t, k), w[0].hex(), pk, '6821' + pk + 'ac'))
            P('#eval chk "%s" %d %d .witnessV0 "%s" "%s" "%s"   -- Lean scriptCode (whole script): expect false' % (tx, k, amt_of(t, k), w[0].hex(), pk, ws.hex()))
open(os.path.join(out_dir, 'CoreTxMismatches.lean'), 'w').write('\n'.join(L) + '\n')
print('ok', len(L))
