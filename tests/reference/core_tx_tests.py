#!/usr/bin/env python3
"""Differential test generator: Bitcoin Core's `src/test/data/tx_valid.json` and `tx_invalid.json`
(revision a773e1e33b349dc819b5a0edc1c7a4839dc73b48) against the Lean transcription
(`BitcoinSer.readTx`, `BitcoinBlockV2.checkTransaction`, `BitcoinTaproot.verifyScriptFull`).

Run with `python3 -I core_tx_tests.py <tx_valid.json> <tx_invalid.json> <out dir>`; it emits
`CoreTxTests.lean` and `core_tx_tests.index.json`.

Harness semantics reproduced here (src/test/transaction_tests.cpp):
  * Each entry is `[[[prevout hash (display order), index, scriptPubKey assembly, amount?], ...],
    serialized tx hex, flags]`. The transaction is deserialized with witness (trailing bytes ignored),
    `CheckTransaction` is run, then for every input `VerifyScript(scriptSig, scriptPubKey, &witness,
    flags, checker(tx, i, amount))` with amount 0 when the entry gives none.
  * tx_valid: the listed flags are the EXCLUDED ones (`~verify_flags` is used); the transaction must
    pass CheckTransaction and every input. tx_invalid: the listed flags are the ones to use; `BADTX`
    means CheckTransaction must fail; otherwise some input must fail VerifyScript.

Inclusion rule (consensus flags only in the Lean): every tx_valid entry is included, verified with the
consensus flags minus the excluded ones (flags only add failure conditions, and Core's harness itself
asserts that removing flags keeps a valid transaction valid). A tx_invalid entry is included iff its
flag set is a subset of the consensus flags (`NONE` and `BADTX` included).
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from core_script_tests import parse_script, parse_flags, lean_flags, CONSENSUS_FLAGS, FLAG_ORDER  # noqa: E402

HEADER = '''import Definitions.Def_BitcoinBlockV2
open BitcoinSer BitcoinSig BitcoinVerify BitcoinTaproot BitcoinBlockV2

/-! Generated by tests/reference/core_tx_tests.py from Bitcoin Core's src/test/data/tx_valid.json and
tx_invalid.json (revision a773e1e33b349dc819b5a0edc1c7a4839dc73b48). Each `#eval` prints `true` iff
the Lean verdict (`.ok` / `.badTx` / `.scriptFail`) is the one Core's harness expects. -/

def hexVal (c : Char) : Nat := if c.isDigit then c.toNat - 48 else c.toLower.toNat - 87
def ofHexL : List Char → Bytes
  | a :: b :: r => BitVec.ofNat 8 (hexVal a * 16 + hexVal b) :: ofHexL r
  | _ => []
def ofHex (s : String) : Bytes := ofHexL s.toList
/-- `⟨p2sh, witness, taproot, dersig, cltv, csv, nulldummy⟩`. -/
def fl (p w t d c s n : Bool) : BitcoinActivation.ScriptFlags := ⟨p, w, t, d, c, s, n⟩

/-- A spent output: prevout hash (internal byte order, hex), index, scriptPubKey (hex), amount. -/
structure Prev where
  hash : String
  n : Nat
  spk : String
  amount : Int

/-- The verdict of the harness. -/
inductive R where
  | badSer      -- the serialization does not deserialize (Core's harness would throw)
  | badTx       -- `CheckTransaction` fails
  | scriptFail  -- some input fails `VerifyScript`
  | ok
  deriving DecidableEq, Repr

/-- Deserialize (ignoring trailing bytes, as `CTransaction(deserialize, TX_WITH_WITNESS, stream)`
does), `CheckTransaction`, then `VerifyScript` on every input with the amount of its prevout (0 when
unknown). -/
def runTx (f : BitcoinActivation.ScriptFlags) (txH : String) (prevs : List Prev) : R :=
  match readTx true (ofHex txH) with
  | none => .badSer
  | some (tx, _) =>
    if !checkTransaction tx then .badTx
    else
      let look (o : OutPoint) : Option (Bytes × Int) :=
        (prevs.find? fun p => ofHex p.hash = o.hash ∧ p.n = o.n).map fun p => (ofHex p.spk, p.amount)
      let spent : List TxOut := tx.vin.map fun i =>
        match look i.prevout with
        | some (spk, a) => ⟨a, spk⟩
        | none => ⟨0, []⟩
      let okAll := (List.range tx.vin.length).all fun i =>
        let inp := tx.vin.getD i ⟨⟨[], 0⟩, [], 0, []⟩
        match look inp.prevout with
        | none => false
        | some (spk, a) => verifyScriptFull spent ⟨f, tx, i, a⟩ inp.scriptSig spk inp.witness
      if okAll then .ok else .scriptFail

'''


def load(path):
    with open(path) as f:
        return json.load(f)


def translate(entry):
    if len(entry) < 2 or not isinstance(entry[0], list):
        return None
    prevs = []
    for inp in entry[0]:
        h = bytes.fromhex(inp[0])[::-1].hex()   # Txid::FromHex: display order -> internal order
        n = int(inp[1]) & 0xffffffff   # uint32_t(vinput[1].getInt<int>())
        spk = parse_script(inp[2]).hex()
        amount = int(inp[3]) if len(inp) >= 4 else 0
        prevs.append((h, n, spk, amount))
    return {'prevs': prevs, 'tx': entry[1], 'flags_str': entry[2], 'raw': entry}


def lean_prevs(prevs):
    return '[' + ', '.join('⟨"%s", %d, "%s", (%d : Int)⟩' % p for p in prevs) + ']'


def collect_comments(data, i):
    """The single-string comment lines immediately preceding entry i."""
    out = []
    j = i - 1
    while j >= 0 and len(data[j]) == 1 and isinstance(data[j][0], str):
        out.insert(0, data[j][0])
        j -= 1
    return ' | '.join(out)


def main():
    valid_path = sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/coretests/tx_valid.json'
    invalid_path = sys.argv[2] if len(sys.argv) > 2 else '/tmp/claude-0/coretests/tx_invalid.json'
    out_dir = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    lines = []
    index = []
    stats = {}
    for kind, path in (('valid', valid_path), ('invalid', invalid_path)):
        data = load(path)
        total = inc = skipped = 0
        for i, e in enumerate(data):
            t = translate(e)
            if t is None:
                continue
            total += 1
            comment = collect_comments(data, i).replace('\n', ' ')
            if kind == 'valid':
                excluded = parse_flags(t['flags_str'])
                flags = CONSENSUS_FLAGS - excluded
                expected = '.ok'
                note = 'excluded ' + (t['flags_str'] or 'NONE')
            else:
                if t['flags_str'] == 'BADTX':
                    flags = set()
                    expected = '.badTx'
                    note = 'BADTX'
                else:
                    flags = parse_flags(t['flags_str'])
                    if not flags <= CONSENSUS_FLAGS:
                        skipped += 1
                        continue
                    expected = '.scriptFail'
                    note = 'flags ' + (t['flags_str'] or 'NONE')
            inc += 1
            tid = '%s#%d' % (kind, i)
            lines.append('#eval runTx %s "%s" %s == %s   -- %s (%s) %s' % (
                lean_flags(flags), t['tx'], lean_prevs(t['prevs']), expected, tid, note, comment))
            index.append({'id': tid, 'kind': kind, 'flags': sorted(flags), 'expected': expected,
                          'comment': comment})
        stats[kind] = (total, inc, skipped)
        print('%s: total %d, included %d, skipped %d' % (kind, total, inc, skipped))
    with open(os.path.join(out_dir, 'CoreTxTests.lean'), 'w') as f:
        f.write(HEADER + '\n'.join(lines) + '\n')
    with open(os.path.join(out_dir, 'reference', 'core_tx_tests.index.json'), 'w') as f:
        json.dump({'stats': stats, 'tests': index}, f, indent=0)


if __name__ == '__main__':
    main()
