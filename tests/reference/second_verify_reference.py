def lean_tx(tx, name):
    ins = ', '.join('⟨⟨hx "%s", %d⟩, [], %d, []⟩' % (i[0].hex(), i[1], i[3]) for i in tx.vin)
    outs = ', '.join('⟨%d, hx "%s"⟩' % (v, spk.hex()) for v, spk in tx.vout)
    return 'def %s : Tx := ⟨%d, [%s], [%s], %d⟩' % (name, tx.version, ins, outs, tx.locktime)


