CTX = {'c0': (0, CONSENSUS_FLAGS), 'c1': (1, CONSENSUS_FLAGS), 'c0nd': (0, CONSENSUS_FLAGS - {'DERSIG'})}


def V(scriptSig, spk, witness, comment, ctx='c0', core_expected=None):
    nIn, flags = CTX[ctx]
    checker = RealChecker(TxChecker(txV, nIn, AMOUNT))
    ok, err = verify_script(scriptSig, spk, witness, flags, checker)
    exp = ok if core_expected is None else core_expected
    w = '[' + ', '.join(lean_hx(e) for e in witness) + ']'
    line = '#eval verifyScript noTap %s (%s) (%s) %s == %s   -- %s' % (ctx, lean_hx(scriptSig), lean_hx(spk), w, str(exp).lower(), comment)
    if not ok: line += ' [' + err + ']'
    L.append(line)


def sig_legacy(d, script_code, hashtype, nIn=0, low_s=True, k=None):
    return ecdsa_sign(d, sighash_legacy(script_code, txV, nIn, hashtype), k=k, low_s=low_s) + bytes([hashtype])


def sig_v0(d, script_code, hashtype, nIn=0):
    return ecdsa_sign(d, sighash_v0(script_code, txV, nIn, hashtype, AMOUNT)) + bytes([hashtype])


p2pk1 = push_bytes(pk1) + bytes([OP_CHECKSIG])
p2pkh1 = bytes([OP_DUP, OP_HASH160]) + push_bytes(hash160(pk1)) + bytes([OP_EQUALVERIFY, OP_CHECKSIG])
p2pk3u = push_bytes(pk3u) + bytes([OP_CHECKSIG])
p2pk3h = push_bytes(pk3h) + bytes([OP_CHECKSIG])


def p2sh(redeem): return bytes([OP_HASH160]) + push_bytes(hash160(redeem)) + bytes([OP_EQUAL])
def wprog(version, program): return bytes([OP_0 if version == 0 else OP_1 + version - 1]) + push_bytes(program)


